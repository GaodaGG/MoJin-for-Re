"""Extract once from the pinned read-only ISO; compile its file extent index.

Runtime reads ordinary resource files, never the ISO container. The original
LBA values remain ABI metadata for this title's file handles and raw extents.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[2]
DEV = ROOT / 'development'
MANIFEST = DEV / 'assets/disc-manifest.json'
DATA = DEV / 'resources/game'
ISO_SHA = '40469759cf0f033f8610f7920ab09b1866040d80b46ff0bdb16b03dfd137b9cb'


def sha(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def manifest():
    m = json.loads(MANIFEST.read_text(encoding='utf-8'))
    assert m['input_iso_sha256'] == ISO_SHA and m['schema'] == 1
    seen = set()
    for e in m['entries']:
        p = PurePosixPath(e['path'])
        assert not p.is_absolute() and '..' not in p.parts and '\\' not in e['path']
        assert e['path'] not in seen and e['path'].isascii()
        assert e['lba'] >= 0 and e['size'] >= 0
        assert e['lba']*2048+e['size'] <= m['physical_bytes']
        seen.add(e['path'])
    return m


def prepare():
    m = manifest()
    rows = ['/* Generated by tools/disc_data.py; fixed input, no runtime ISO reader. */',
            '#ifndef MOJIN_DISC_MANIFEST_H', '#define MOJIN_DISC_MANIFEST_H',
            'typedef struct { const char *path; uint32_t lba, size; int directory; } MojinDiscFile;',
            f'#define MOJIN_DISC_SECTORS {m["physical_bytes"] // 2048}u',
            f'#define MOJIN_DISC_MANIFEST_SHA "{sha(MANIFEST)}"',
            'static const MojinDiscFile s_files[] = {']
    for e in m['entries']:
        rows.append('    {%s, %du, %du, %d},' %
                    (json.dumps(e['path']), e['lba'], e['size'], e['directory']))
    rows += ['};', '#define MOJIN_DISC_COUNT (sizeof(s_files)/sizeof(s_files[0]))', '#endif', '']
    p = DEV / 'generated/runtime/disc_manifest.h'
    p.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(rows)
    if not p.exists() or p.read_text(encoding='utf-8') != text:
        p.write_text(text, encoding='utf-8', newline='\n')


def verify(root=DATA):
    m = manifest()
    for e in m['entries']:
        if not e['directory']:
            p = root / e['path']
            assert p.is_file() and p.stat().st_size == e['size'] and sha(p) == e['sha256'], str(p)
    return m


def extract(shared=None):
    from inspect_input import Iso
    iso_path = ROOT / '魔法禁书目录.iso'
    assert sha(iso_path) == ISO_SHA, 'Wrong input version'
    iso = Iso(iso_path)
    entries = []
    identical = {}
    for e in iso.entries:
        assert e['within_image'] and not e['flags'] & 0x80, 'Unsupported extent'
        item = dict(path=e['path'].lstrip('/'), lba=e['extent'], size=e['size'], directory=e['directory'])
        target = DATA / item['path']
        if e['directory']:
            target.mkdir(parents=True, exist_ok=True)
        else:
            data = iso.read(e['offset'], e['size'])
            digest = hashlib.sha256(data).hexdigest()
            item['sha256'] = digest
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.exists():
                assert sha(target) == digest, f'Preserve changed resource: {target}'
            elif shared and (shared / item['path']).is_file() and sha(shared / item['path']) == digest:
                os.link(shared / item['path'], target)
            elif digest in identical:
                os.link(identical[digest], target)
            else:
                with target.open('xb') as f:
                    f.write(data)
            assert sha(target) == digest
            identical[digest] = target
        entries.append(item)
    iso.file.close()
    m = dict(schema=1, input_iso_sha256=ISO_SHA, physical_bytes=iso.size, entries=entries,
             runtime='Loose immutable files; original LBA retained only as file-access metadata. Unmapped raw disk reads fail explicitly.')
    text = json.dumps(m, ensure_ascii=False, indent=2)+'\n'
    if MANIFEST.exists():
        assert MANIFEST.read_text(encoding='utf-8') == text, 'Manifest changed; preserve and review'
    else:
        MANIFEST.write_text(text, encoding='utf-8', newline='\n')
    verify()
    prepare()
    print(json.dumps(dict(root=str(DATA), files=len(identical), entries=len(entries),
                         logical_bytes=sum(e['size'] for e in entries if not e['directory']),
                         manifest_sha256=sha(MANIFEST), original_iso_unchanged=sha(iso_path)==ISO_SHA), indent=2))


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('action', choices=['extract', 'verify', 'header'])
    p.add_argument('--reuse-verified', type=Path, help='Compare every resource with fresh ISO bytes before sharing an existing identical regular file')
    args = p.parse_args()
    if args.reuse_verified and args.action != 'extract': p.error('--reuse-verified applies only to extract')
    if args.action == 'extract': extract(args.reuse_verified.resolve() if args.reuse_verified else None)
    elif args.action == 'verify': verify(); print('All resource hashes match the pinned input.')
    else: prepare()
