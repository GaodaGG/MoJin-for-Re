"""Build a portable pipeline-description catalog from completed, pinned probes.

No driver cache bytes or graphics resources are imported. Unknown states always
retain the renderer's normal creation path. Catalog scope is recorded explicitly.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEV = ROOT / 'development'
FIELDS = ('blend_on', 'srcf', 'dstf', 'eq', 'cull', 'ztest', 'zwrite', 'zfunc', 'cmask', 'tnl', 'azero', 'zbias')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def emit():
    catalog = json.loads((DEV/'assets/pipeline-catalog.json').read_text(encoding='utf-8'))
    assert catalog['schema'] == 1 and catalog['fields'] == list(FIELDS)
    for name, expected in catalog['renderer_inputs'].items():
        path = (ROOT/name).resolve()
        assert path.is_relative_to(DEV/'third_party/nakagawa') and sha(path) == expected, name
    seen = set()
    lines = ['/* Generated by pipeline_catalog.py. Descriptions, never opaque driver cache data. */',
             f'#define MOJIN_CATALOG_SHADER_SET UINT64_C(0x{catalog["shader_set"]})',
             'static const struct { PipeKey key; int rmw; } mojin_pipeline_catalog[] = {']
    for row in catalog['pipelines']:
        key, rmw = row['key'], row['rmw']
        assert len(key) == 12 and all(type(v) is int and 0 <= v <= 255 for v in key)
        assert rmw in (0, 1, 2) and (tuple(key), rmw) not in seen
        assert key[0] <= 1 and key[4] <= 3 and key[5] <= 1 and key[6] <= 1
        assert key[7] <= 7 and key[8] <= 15 and key[9] <= 1 and key[10] <= 1 and key[11] <= 2
        seen.add((tuple(key), rmw))
        lines.append('    {{' + ','.join(f'.{name}={v}' for name,v in zip(FIELDS,key)) + '},' + str(rmw) + '},')
    lines.append('};\n')
    output = DEV/'generated/runtime/pipeline_catalog.h'
    data = '\n'.join(lines)
    if not output.exists() or output.read_text(encoding='utf-8') != data:
        output.write_text(data, encoding='utf-8', newline='\n')
    return catalog


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('runs', nargs='+', type=Path)
    args = parser.parse_args()
    records, keys, shader_sets = [], set(), set()
    for item in args.runs:
        run = item.resolve()
        assert run.is_relative_to(DEV/'tests/runs')
        meta = json.loads((run/'run.json').read_text(encoding='utf-8'))
        assert meta['exit_code'] == 0 and not meta['timed_out']
        assert meta['image_sha256'] == 'aa17cb3f96155592be82a9a0629ec876b61169e3dd3e7ab4e5d8b5e6da53d2f4'
        trace = run/'pipelines.jsonl'
        for line in trace.read_text(encoding='utf-8').splitlines():
            row = json.loads(line)
            assert row['result'] == 0 and row['phase'] == 'draw'
            keys.add((tuple(row['key']),row['rmw']))
            shader_sets.add(row['shader_set'])
        records.append(dict(run=str(run.relative_to(ROOT)), run_sha256=sha(run/'run.json'),
                            trace_sha256=sha(trace), executable_sha256=meta['executable_sha256'],
                            image_sha256=meta['image_sha256']))
    assert len(shader_sets) == 1
    gpu = DEV/'third_party/nakagawa/src/rt/gpu_sdl3vk'
    import re
    renderer_files = [gpu/'ge_gpu.c']
    for name in re.findall(r'#include "([^"]+)"', renderer_files[0].read_text(encoding='utf-8')):
        if name in ('psp_vert.inc','psp_frag.inc','psp_frag_rmw.inc','psp_tnl_vert.inc'):
            renderer_files.append((gpu/name).resolve())
    catalog = dict(schema=1, fields=list(FIELDS), shader_set=next(iter(shader_sets)),
        input_iso_sha256='40469759cf0f033f8610f7920ab09b1866040d80b46ff0bdb16b03dfd137b9cb',
        source_runs=records, renderer_inputs={str(p.relative_to(ROOT).as_posix()):sha(p) for p in renderer_files},
        scope='Opening, menus, and one night-bridge vs-CPU battle. Other effects use normal misses; no all-game coverage claim.',
        pipelines=[dict(key=list(k),rmw=m) for k,m in sorted(keys)])
    (DEV/'assets/pipeline-catalog.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')
    emit()
    print(json.dumps(dict(entries=len(keys),shader_set=catalog['shader_set'],renderer_inputs=len(renderer_files))))


if __name__ == '__main__':
    main()
